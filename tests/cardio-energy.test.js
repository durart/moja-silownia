const assert=require('node:assert/strict');
const core=require('../modules/cardio-core.js');
const energy=require('../modules/cardio-energy.js');
const meta={id:'a',at:'2026-11-26T08:00:00Z'};
const activity=(id,metrics)=>core.createActivity('cardio-'+id,{durationSeconds:1800,...metrics},meta);
const walk=activity('treadmill-walk',{speedKmh:5.5,inclinePercent:10});
const flat=activity('treadmill-walk',{speedKmh:5.5,inclinePercent:0});
assert.equal(energy.activityMet(walk).method,'acsm');
assert.ok(Math.abs(energy.activityMet(walk).met-8.333333333333334)<1e-9);
assert.ok(energy.activityMet(walk).met>energy.activityMet(flat).met);
assert.equal(energy.activityMet(activity('treadmill-run',{speedKmh:10,inclinePercent:0})).method,'acsm');
assert.equal(energy.activityMet(activity('treadmill-walk',{speedKmh:5.5})).method,'reference-met');
assert.equal(energy.activityMet(activity('treadmill-walk',{speedKmh:2,inclinePercent:10})).method,'reference-met');
assert.equal(energy.activityMet(activity('treadmill-walk',{speedKmh:5.5,inclinePercent:-5})).method,'reference-met');
assert.equal(energy.activityMet(activity('bike',{})).met,6.8);
assert.equal(energy.activityMet(activity('bike',{rpe:2})).met,4);
assert.equal(energy.activityMet(activity('bike',{rpe:8})).met,8);
assert.equal(energy.activityMet(activity('elliptical',{})).met,5);
assert.equal(energy.activityMet(activity('rowing',{})).met,5);
assert.equal(energy.activityMet(activity('stairmaster',{})).met,9.3);
assert.equal(energy.activityMet(activity('bike',{speedKmh:45})).met,6.8);
assert.equal(energy.activityMet(activity('bike',{})).assumedIntensity,true);
const sets=Array.from({length:15},()=>({exerciseId:'seed-0',weight:50,reps:10}));
const legacy=energy.estimate({sets,durationSeconds:3600},100);
assert.deepEqual(legacy,{total:350,active:250,met:3.5});
const cardio=energy.estimate({sets:[],cardio:[walk],durationSeconds:1800},100);
assert.equal(cardio.total,417);
assert.equal(cardio.active,367);
assert.equal(cardio.strength.durationSeconds,0);
assert.equal(cardio.idle.durationSeconds,0);
const mixed=energy.estimate({sets,cardio:[walk],durationSeconds:5400},100);
assert.equal(mixed.strength.durationSeconds,3600);
assert.equal(mixed.cardio.durationSeconds,1800);
assert.equal(mixed.total,767);
assert.equal(mixed.active,617);
assert.equal(mixed.strength.active,250);
assert.equal(mixed.effectiveSeconds,5400);
const idle=energy.estimate({sets:[],cardio:[walk],durationSeconds:2400},100);
assert.equal(idle.idle.durationSeconds,600);
assert.equal(idle.active,cardio.active);
const adjusted=energy.estimate({sets,cardio:[walk],durationSeconds:1200},100);
assert.equal(adjusted.durationAdjusted,true);
assert.equal(adjusted.strengthDurationUnknown,true);
assert.equal(adjusted.active,cardio.active);
assert.equal(adjusted.effectiveSeconds,1800);
assert.throws(()=>energy.estimate({sets:[],cardio:[walk,walk],durationSeconds:3600},100));
assert.throws(()=>energy.estimate({sets:[],cardio:[walk],durationSeconds:1800},0));
assert.deepEqual(energy.estimate({sets:[],durationSeconds:0},100),{total:0,active:0,met:0});
assert.ok(energy.estimate({sets:[],cardio:[walk],durationSeconds:1800},80).active<cardio.active);
console.log('Cardio energy assertions passed');
