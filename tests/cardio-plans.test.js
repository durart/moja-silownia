const assert=require('node:assert/strict');
const plans=require('../modules/cardio-plans.js');
const core=require('../modules/cardio-core.js');
const energy=require('../modules/cardio-energy.js');
const ui=require('../modules/cardio-ui.js');
require('../summary-core.js');
const walk='cardio-treadmill-walk',bike='cardio-bike',strength='seed-14';
const target={measurementType:'cardio',durationSeconds:1800,speedKmh:5.5,inclinePercent:10};
assert.deepEqual(plans.keys(walk),['durationSeconds','speedKmh','inclinePercent']);
assert.deepEqual(plans.keys(bike),['durationSeconds','speedKmh']);
assert.deepEqual(plans.keys('cardio-rowing'),['durationSeconds']);
assert.deepEqual(plans.keys(strength),[]);
assert.deepEqual(plans.normalizeTarget(walk,target),target);
assert.equal(plans.normalizeTarget(strength,target),null);
assert.equal(plans.normalizeTarget(walk,{sets:3,reps:12}),null);
assert.throws(()=>plans.normalizeTarget(walk,{...target,durationSeconds:-1}));
assert.throws(()=>plans.normalizeTarget(walk,{...target,speedKmh:'5.5'}));
assert.equal(plans.duplicates([strength,walk,bike,strength]),false);
assert.equal(plans.duplicates([walk,strength,walk]),true);
assert.equal(plans.duplicates([]),false);
const plan={id:1,exerciseIds:[strength,walk],targets:[{sets:3,reps:12},target]};
assert.equal(plans.validatePlans([plan]),undefined);
assert.throws(()=>plans.validatePlans([{...plan,exerciseIds:[walk,walk]}]));
assert.throws(()=>plans.validatePlans([{...plan,targets:[target,target]}]));
const rec=plans.recommendation(walk,[],target,{now:Date.parse('2026-11-26')});
assert.equal(rec.reason,'plan-target');
assert.deepEqual(rec.target,{durationSeconds:1800,speedKmh:5.5,inclinePercent:10});
assert.ok(ui.recommendationHtml(rec).includes('Cel zapisany w planie'));
const state={activePlan:1,startedAt:'session',plans:[plan],manualExerciseIds:[],planExtraExerciseIds:[bike],hiddenWorkoutSlots:[],workoutSwaps:{}};
assert.equal(plans.activeSlot(state,walk),1);
assert.equal(plans.activeSlot(state,bike),null);
assert.equal(plans.inContext(state,walk),true);
assert.equal(plans.inContext(state,bike),true);
assert.equal(plans.inContext(state,strength),false);
assert.equal(plans.inContext({...state,hiddenWorkoutSlots:[1]},walk),false);
assert.equal(plans.inContext({...state,startedAt:null},walk),false);
assert.equal(plans.inContext({...state,activePlan:null,manualStarted:true,manualExerciseIds:[walk]},walk),true);
assert.equal(plans.inContext({...state,activePlan:null,manualStarted:false,manualExerciseIds:[walk]},walk),false);
const activity=core.createActivity(walk,{durationSeconds:1800,speedKmh:5.5,inclinePercent:10},{id:'walk-1',at:'2026-11-26T08:00:00Z'});
const session={id:1,date:'2026-11-26T08:30:00Z',planName:'A',durationSeconds:3600,sets:[{exerciseId:strength,name:'Wyciskanie',weight:60,reps:12,pr:['weight']}],cardio:[activity]};
session.calories=energy.estimate(session,100);
const snapshot=JSON.stringify(session),model=globalThis.SportSummaryCore.build(session);
assert.equal(model.exerciseCount,2);
assert.equal(model.setCount,1);
assert.equal(model.volume,720);
assert.equal(model.reps,12);
assert.equal(model.prCount,1);
assert.equal(model.cardioSeconds,1800);
assert.equal(model.cardioActiveKcal,session.calories.cardio.active);
assert.equal(model.groups[1].measurementType,'cardio');
assert.equal(model.groups[1].count,0);
assert.equal(model.groups[1].sets.length,0);
assert.equal(model.groups[1].name,'Bieżnia – marsz');
assert.equal(JSON.stringify(session),snapshot);
const cardioOnly=globalThis.SportSummaryCore.build({...session,sets:[]});
assert.equal(cardioOnly.setCount,0);
assert.equal(cardioOnly.volume,0);
assert.equal(cardioOnly.exerciseCount,1);
const old=globalThis.SportSummaryCore.build({...session,cardio:undefined});
assert.equal(old.exerciseCount,1);
assert.equal(old.cardioSeconds,undefined);
console.log('Cardio plan and summary assertions passed');
