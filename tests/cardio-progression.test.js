const assert=require('node:assert/strict');
const progression=require('../modules/cardio-progression.js');
const core=require('../modules/cardio-core.js');
const ui=require('../modules/cardio-ui.js');
const now=Date.parse('2026-11-26T12:00:00Z');
const walk='cardio-treadmill-walk',run='cardio-treadmill-run',bike='cardio-bike';
function session(id,day,metrics,sessionMode='standard'){
 const date='2026-11-'+day+'T08:00:00Z';
 return {date,sessionMode,sets:[],cardio:[core.createActivity(id,metrics,{id:id+'-'+day,at:date})]};
}
const base={durationSeconds:1200,speedKmh:5.5,inclinePercent:5,rpe:4};
const a=session(walk,'24',base),b=session(walk,'22',base);
const suggest=(id,sessions,options={})=>progression.suggest(id,sessions,{now,...options});
assert.equal(suggest(walk,[]).action,'initial');
assert.equal(suggest('seed-14',[a]),null);
assert.equal(suggest(walk,[a]).reason,'need-two-sessions');
const increase=suggest(walk,[b,a]);
assert.equal(increase.action,'increase');
assert.equal(increase.changedMetric,'durationSeconds');
assert.equal(increase.target.durationSeconds,1260);
assert.equal(increase.target.speedKmh,5.5);
assert.equal(increase.target.inclinePercent,5);
assert.deepEqual(progression.initialDraft(increase),{speedKmh:5.5,inclinePercent:5});
assert.ok(!('durationSeconds' in progression.initialDraft(increase)));
assert.equal(suggest(walk,[a,b],{sessionMode:'recovery'}).reason,'recovery');
const recovery=session(walk,'25',{...base,durationSeconds:600,speedKmh:3,rpe:2},'recovery');
assert.equal(suggest(walk,[a,recovery,b]).sourceActivityId,a.cardio[0].id);
assert.equal(suggest(walk,[session(walk,'25',{...base,rpe:8}),a,b]).reason,'high-rpe');
assert.equal(suggest(walk,[session(walk,'25',{...base,rpe:6}),a,b]).reason,'effort');
assert.equal(suggest(walk,[session(walk,'25',{...base,rpe:null}),a,b]).reason,'missing-rpe');
assert.equal(suggest(walk,[session(walk,'25',{...base,inclinePercent:8}),a,b]).reason,'not-comparable');
assert.equal(suggest(walk,[session(walk,'25',{...base,durationSeconds:900}),a,b]).reason,'not-comparable');
assert.equal(suggest(walk,[session(walk,'25',{durationSeconds:1200,rpe:4}),session(walk,'24',{durationSeconds:1200,rpe:4})]).reason,'not-comparable');
assert.equal(suggest(walk,[session(walk,'02',base),session(walk,'01',base)]).reason,'history-gap');
assert.equal(suggest(walk,[a,{...b,date:a.date}]).reason,'need-two-sessions');
const longer={...base,durationSeconds:1800};
const incline=suggest(walk,[session(walk,'24',longer),session(walk,'22',longer)]);
assert.equal(incline.changedMetric,'inclinePercent');
assert.deepEqual(incline.target,{durationSeconds:1800,speedKmh:5.5,inclinePercent:5.5});
const steep={...longer,inclinePercent:10};
const speed=suggest(walk,[session(walk,'24',steep),session(walk,'22',steep)]);
assert.equal(speed.changedMetric,'speedKmh');
assert.equal(speed.target.speedKmh,5.6);
const max={...steep,speedKmh:6};
assert.equal(suggest(walk,[session(walk,'24',max),session(walk,'22',max)]).reason,'at-limit');
const runMetrics={durationSeconds:1800,speedKmh:9,inclinePercent:0,rpe:4};
assert.equal(suggest(run,[session(run,'24',runMetrics),session(run,'22',runMetrics)]).target.speedKmh,9.2);
const bikeMetrics={durationSeconds:1800,speedKmh:18,rpe:4};
assert.equal(suggest(bike,[session(bike,'24',bikeMetrics),session(bike,'22',bikeMetrics)]).target.durationSeconds,1890);
const bikeMax={...bikeMetrics,durationSeconds:2700};
assert.equal(suggest(bike,[session(bike,'24',bikeMax),session(bike,'22',bikeMax)]).reason,'at-limit');
const bikeFaster={...bikeMetrics,speedKmh:25};
assert.equal(suggest(bike,[session(bike,'24',bikeFaster),session(bike,'22',bikeMetrics)]).reason,'not-comparable');
const html=ui.renderCard(walk,1,{draft:progression.initialDraft(increase),recommendation:increase});
assert.ok(html.includes('Asystent kardio'));
assert.ok(html.includes('Cel: 00:21:00'));
assert.ok(/data-cardio-field="durationSeconds"[^>]*value=""/.test(html));
assert.ok(html.includes('data-cardio-field="speedKmh"'));
assert.ok(!ui.renderCard(walk,1,{activity:a.cardio[0],recommendation:increase}).includes('Asystent kardio'));
const source=JSON.stringify([a,b]);suggest(walk,[a,b]);assert.equal(JSON.stringify([a,b]),source);
console.log('Cardio progression tests passed');
