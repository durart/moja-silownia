const assert=require('node:assert/strict');
const catalog=require('../modules/cardio-catalog.js');
const core=require('../modules/cardio-core.js');
function testCore(core, catalog, check, throws) {
 const meta={id:'activity-1',at:'2026-11-26T08:00:00Z'};
 const walk=core.createActivity('cardio-treadmill-walk',{durationSeconds:1800,speedKmh:5.5,inclinePercent:10,rpe:5},meta);
 check(walk.distanceMeters===2750,'Distance calculation');
 check(walk.estimatedMetrics.includes('distanceMeters'),'Estimated distance marker');
 check(!('weight' in walk)&&!('reps' in walk)&&!('calories' in walk),'No strength or manual calorie fields');
 check(core.createActivity('cardio-treadmill-walk',{durationSeconds:1800,distanceMeters:2700,speedKmh:5.5},meta).distanceMeters===2700,'Manual distance preserved');
 check(core.createActivity('cardio-bike',{durationSeconds:1200,distanceMeters:6000},meta).speedKmh===18,'Speed calculated');
 check(core.createActivity('cardio-rowing',{durationSeconds:600,distanceMeters:2000},meta).paceSecondsPer500m===150,'Rowing pace calculated');
 check(core.createActivity('cardio-stairmaster',{durationSeconds:300,floors:20},meta).floors===20,'Floors');
 check(catalog.exercises.every(ex=>core.createActivity(ex.id,{durationSeconds:60},meta).durationSeconds===60),'Duration-only for all');
 throws(()=>core.createActivity('seed-14',{durationSeconds:30},meta),'Reject non-cardio');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:0},meta),'Reject zero duration');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:NaN},meta),'Reject NaN');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,resistance:5},meta),'Reject resistance');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,heartRate:120},meta),'Reject heart rate');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,calories:200},meta),'Reject manual calories');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,rpe:11},meta),'Reject invalid RPE');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,distanceMeters:-1},meta),'Reject negative distance');
 throws(()=>core.createActivity('cardio-bike',{durationSeconds:60,inclinePercent:10},meta),'Reject unsupported metric');
 const state={sessions:[{sets:[{exerciseId:'seed-14',durationSeconds:30}]},{sets:[],cardio:[walk]}],active:[]};
 const before=JSON.stringify(state);
 check(core.validateState(state)===state&&JSON.stringify(state)===before,'Legacy and mixed state unchanged');
 throws(()=>core.validateActivities([walk,walk]),'Duplicate id');
 throws(()=>core.validateActivities([{...walk,estimatedMetrics:['rpe']}]),'Reject invalid estimate marker');
 const timer=core.startTimer({exerciseId:'cardio-bike',workoutId:'workout-1',activityId:'activity-1'},1000);
 check(core.elapsedSeconds(timer,6500)===5,'Elapsed running time');
 const paused=core.pauseTimer(timer,6500);
 check(core.elapsedSeconds(paused,100000)===5,'Pause freezes time');
 const restored=JSON.parse(JSON.stringify(paused));
 const resumed=core.resumeTimer(restored,100000);
 check(core.elapsedSeconds(resumed,104500)===10,'Resume preserves milliseconds');
 check(core.stopTimer(resumed,104500).durationSeconds===10,'Stop returns activity duration');
 check(timer.status==='running'&&paused.status==='paused','Timer immutable');
 throws(()=>core.resumeTimer(timer,2000),'Reject duplicate resume');
 throws(()=>core.pauseTimer(paused,8000),'Reject duplicate pause');
 throws(()=>core.elapsedSeconds(resumed,99000),'Reject clock reversal');
 throws(()=>core.stopTimer(timer,1500),'Reject sub-second stop');
 check(core.elapsedSeconds(timer,100000000)===86400,'Duration cap');
}
testCore(core,catalog,(value,message)=>assert.ok(value,message),(fn,message)=>assert.throws(fn,undefined,message));
console.log('Cardio core: 30 assertions passed');
