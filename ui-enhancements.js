/* Atlas categories are sourced from the same ExerciseCatalog used by the workout and plan pickers. */
const uiMuscleGroups = ExerciseCatalog.categories.map(({id,label,art})=>[id,label,art]);
let uiCatalogGroup = null;
let uiCatalogOrder = 'recent';
function uiExerciseMatchesGroup(e,group){
 if(group===null||group==='')return true;
 return ExerciseCatalog.matches(e,group);
}
function uiExerciseThumb(e){
  const cardio=window.MojaCardioUI.thumbnail(e?.id);if(cardio)return cardio;
  const match=/^seed-(\d+)$/.exec(String(e.id||''));
  let index=match?Number(match[1]):-1;
  // Existing/imported exercises can have alternative ids. Match only exact catalog names.
  if(index<0){
    const seed=seeds.find(x=>x.name===e.name);
    if(seed){const m=/^seed-(\d+)$/.exec(seed.id);if(m)index=Number(m[1]);}
  }
  if(index>=0&&index<103){
    const x=(index%8)*100/7, y=Math.floor(index/8)*100/12;
    return `<span class="ui-thumb-sprite" style="background-position:${x.toFixed(5)}% ${y.toFixed(5)}%"></span>`;
  }
  const pos={'Klatka piersiowa':0,'Plecy':1,'Barki':2,'Triceps':3,'Biceps':4,'Przedramiona':5,'Nogi':6,'Brzuch':7,'Łydki':8,'Inne':9,'Kardio':11}[e.group]??10;
  const fx=(pos%3)*50,fy=Math.floor(pos/3)*100/3;
  return `<span class="ui-thumb-fallback" style="background-position:${fx}% ${fy.toFixed(5)}%"></span>`;
}
function uiCatalogChoose(group){
  uiCatalogGroup=group;
  document.getElementById('search').value='';
  renderCatalog();
  document.getElementById('catalogTitle').scrollIntoView({block:'start',behavior:'auto'});
}
function uiCatalogBack(){
  if(uiCatalogGroup!==null){uiCatalogGroup=null;document.getElementById('search').value='';renderCatalog()}
  else tab('dashboard');
}
function uiCatalogSort(){
  uiCatalogOrder=uiCatalogOrder==='recent'?'alpha':'recent';
  renderCatalog();
}
// Same muscle-selection presentation as the workout exercise picker.
function renderMuscleTiles(){
 const el=document.getElementById('muscleTiles');
 if(!el)return;
 el.innerHTML=uiMuscleGroups.map(([group,label,idx])=>{
  const count=ExerciseCatalog.count(state.exercises,group);
  return `<button class="catalog-muscle-button" type="button" data-muscle="${safe(group)}" onclick="uiCatalogChoose(this.dataset.muscle)"><span class="catalog-full-icon catalog-source-${idx}" aria-hidden="true"></span><strong>${safe(label)}</strong><small>${count} ćw.</small></button>`;
 }).join('');
}
// Retained for backward compatibility with the previous catalog handlers.
function selectMuscle(group){uiCatalogChoose(group||'__all__')}
function renderCatalog(){
 const grid=document.getElementById('muscleTiles'),list=document.getElementById('catalogList');
 if(!grid||!list)return;
 const q=document.getElementById('search').value.trim().toLocaleLowerCase('pl');
 const showList=uiCatalogGroup!==null||q.length>0;
 const current=uiMuscleGroups.find(x=>x[0]===uiCatalogGroup);
 const title=document.getElementById('catalogTitle');
 title.textContent=current?current[1]:(q?'Wszystkie ćwiczenia':'Wybierz partię ciała');
 const back=document.getElementById('catalogBack');
 back.hidden=!showList;
 const sort=document.getElementById('catalogSort');
 sort.title=uiCatalogOrder==='recent'?'Ostatnio używane najpierw. Zmień na alfabetycznie':'Alfabetycznie. Zmień na ostatnio używane';
 sort.textContent=uiCatalogOrder==='recent'?'☰':'A–Z';
 grid.hidden=showList;
 list.hidden=!showList;
 if(!showList){renderMuscleTiles();list.innerHTML='';return}
 let hits=state.exercises.filter(e=>uiExerciseMatchesGroup(e,uiCatalogGroup) &&
  (e.name+' '+e.group+' '+e.equipment).toLocaleLowerCase('pl').includes(q));
 hits=uiCatalogOrder==='recent'?sortExercisesByUse(hits):[...hits].sort((a,b)=>a.name.localeCompare(b.name,'pl'));
 list.innerHTML=`<p class="catalog-count">${hits.length} ćwiczeń · ${uiCatalogOrder==='recent'?'ostatnio używane najpierw':'kolejność alfabetyczna'}</p>`+
 (hits.length?hits.map(e=>`<div class="catalog-exercise-row">
  <button class="catalog-exercise-main" type="button" data-id="${safe(e.id)}" onclick="uiCatalogAdd(this.dataset.id)" title="Dodaj do planu: ${safe(e.name)}">
   <span class="catalog-thumb" aria-hidden="true">${window.CALISTHENICS_ICON_SVGS?.[e.id]||uiExerciseThumb(e)}</span>
   <span class="catalog-exercise-label">${safe(e.name)}<small>${safe(e.equipment||e.group)} · dotknij, aby dodać do planu</small></span>
  </button>
  <button class="catalog-technique" type="button" data-id="${safe(e.id)}" onclick="openTechnique(this.dataset.id)" title="Zobacz technikę" aria-label="Zobacz technikę: ${safe(e.name)}">⋮</button>
  </div>`).join(''):'<p class="catalog-empty">Brak ćwiczeń w wybranej kategorii.</p>');
}
function uiCatalogAdd(id){
 if(!state.exercises.some(e=>e.id===id))return;
 addFromCatalog(id);
}
